#Simple Calculator
num_1 = float(input("Enter the first number: "))
num_2 = float(input("Enter the second number: "))
operator = input("Choose the operator (+, -, *, /): ").strip()

if operator == "+":
    print(f"Addition of {num_1:g} and {num_2:g} is:", num_1 + num_2)
elif operator == "-":
    print(f"Subtraction of {num_1:g} and {num_2:g} is:", num_1 - num_2)
elif operator == "*":
    print(f"Multiplication of {num_1:g} and {num_2:g} is:", num_1 * num_2)
elif operator == "/":
    if num_2 == 0:
        print("Cannot divide by zero")
    else:
        print(f"Division of {num_1:g} and {num_2:g} is:", round(num_1 / num_2, 2))
else:
    print("Invalid operator")