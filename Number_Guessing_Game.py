#Number_Guessing_Game
import random

secret = random.randint(1, 10)
guess = int(input("Guess a number between 1 and 10: "))

if guess < 1 or guess > 10:
    print("Please guess between 1 and 10")
elif guess == secret:
    print("correct")
elif guess > secret:
    print("too high")
else:
    print("too low")